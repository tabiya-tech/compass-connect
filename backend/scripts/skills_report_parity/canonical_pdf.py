"""
Canonical (normalized) representation of a skills report PDF, used to compare PDFs generated by different engines
(react-pdf in the frontend, reportlab in the backend).

The raw bytes of two PDFs from different engines are never identical (object order, font subsetting, compression,
metadata), so the comparison is done on what the reader sees:

  content (hashed):
    - page count and page size
    - per page, the text lines in reading order (top -> bottom, left -> right), each line as a list of styled spans
      (text with collapsed whitespace, font (subset prefix removed), size, colour)
    - per page, the images (rendered size)
  layout (compared with a tolerance, not hashed):
    - per line: x of the first glyph and the baseline
    - per image: position
    - per page: the boxes drawn by vector graphics (borders/dividers), merged by overlap
"""
import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path

from pdfminer.high_level import extract_pages
from pdfminer.layout import LAParams, LTChar, LTCurve, LTFigure, LTImage, LTLine, LTRect

_BASELINE_PRECISION = 1  # decimals used to group glyphs on the same baseline


@dataclass
class _Glyph:
    text: str
    x: float
    baseline: float
    font: str
    size: float
    color: str


@dataclass
class CanonicalPdf:
    content: dict
    layout: dict = field(default_factory=dict)

    @property
    def content_hash(self) -> str:
        return hashlib.sha256(json.dumps(self.content, sort_keys=True, ensure_ascii=False).encode("utf-8")).hexdigest()


def _normalize_font(name: str) -> str:
    return name.split("+", 1)[1] if "+" in name else name


def _normalize_color(ncolor) -> str:
    if ncolor is None:
        return "#000000"
    if isinstance(ncolor, (int, float)):
        ncolor = (ncolor,)
    values = list(ncolor)
    if len(values) == 1:
        values = values * 3
    if len(values) == 4:  # CMYK
        c, m, y, k = values
        values = [(1 - c) * (1 - k), (1 - m) * (1 - k), (1 - y) * (1 - k)]
    return "#" + "".join(f"{round(float(v) * 255):02X}" for v in values[:3])


def _walk(obj):
    yield obj
    if isinstance(obj, (LTFigure,)) or hasattr(obj, "_objs"):
        for child in getattr(obj, "_objs", []):
            yield from _walk(child)


def _lines_from_glyphs(glyphs: list[_Glyph]) -> list[dict]:
    by_baseline: dict[float, list[_Glyph]] = {}
    for g in glyphs:
        by_baseline.setdefault(round(g.baseline, _BASELINE_PRECISION), []).append(g)
    lines = []
    for baseline in sorted(by_baseline, reverse=True):  # top -> bottom
        line_glyphs = sorted(by_baseline[baseline], key=lambda g: g.x)
        spans: list[dict] = []
        pending_space = False
        for g in line_glyphs:
            if g.text.isspace() or g.text == "":
                pending_space = True
                continue
            style = (g.font, g.size, g.color)
            if spans and (spans[-1]["font"], spans[-1]["size"], spans[-1]["color"]) == style:
                spans[-1]["text"] += (" " if pending_space else "") + g.text
            else:
                spans.append({"text": (" " if pending_space and spans else "") + g.text, "font": g.font,
                              "size": g.size, "color": g.color})
            pending_space = False
        if spans:
            first = next(g for g in line_glyphs if not g.text.isspace())
            actual_baseline = sum(g.baseline for g in line_glyphs) / len(line_glyphs)
            lines.append({"spans": spans, "x": round(first.x, 2), "baseline": round(actual_baseline, 2)})
    return lines


def _merge_boxes(boxes: list[tuple[float, float, float, float]], tolerance: float = 0.75) -> list[list[float]]:
    merged: list[list[float]] = []
    for box in sorted(boxes):
        x0, y0, x1, y1 = box
        for m in merged:
            if x0 <= m[2] + tolerance and x1 >= m[0] - tolerance and y0 <= m[3] + tolerance and y1 >= m[1] - tolerance:
                m[0], m[1], m[2], m[3] = min(m[0], x0), min(m[1], y0), max(m[2], x1), max(m[3], y1)
                break
        else:
            merged.append([x0, y0, x1, y1])
    # merging can create new overlaps, repeat until stable
    if len(merged) != len(boxes):
        return _merge_boxes([tuple(m) for m in merged], tolerance)
    return [[round(v, 1) for v in m] for m in merged]


def canonicalize_pdf(path: Path) -> CanonicalPdf:
    pages_content = []
    pages_layout = []
    page_size = None
    for page in extract_pages(str(path), laparams=LAParams()):
        page_size = [round(page.width, 1), round(page.height, 1)]
        glyphs: list[_Glyph] = []
        images = []
        graphics = []
        for obj in _walk(page):
            if isinstance(obj, LTChar):
                glyphs.append(_Glyph(text=obj.get_text(), x=obj.matrix[4], baseline=obj.matrix[5],
                                     font=_normalize_font(obj.fontname), size=round(obj.size, 1),
                                     color=_normalize_color(obj.graphicstate.ncolor)))
            elif isinstance(obj, LTImage):
                images.append({"width": round(obj.width, 1), "height": round(obj.height, 1),
                               "x": round(obj.x0, 2), "top": round(page.height - obj.y1, 2)})
            elif isinstance(obj, (LTRect, LTLine, LTCurve)):
                graphics.append((obj.x0, obj.y0, obj.x1, obj.y1))
        lines = _lines_from_glyphs(glyphs)
        images.sort(key=lambda i: (i["top"], i["x"]))
        pages_content.append({
            "lines": [line["spans"] for line in lines],
            "images": [[i["width"], i["height"]] for i in images],
        })
        pages_layout.append({
            "lines": [{"x": line["x"], "baseline": line["baseline"]} for line in lines],
            "images": [{"x": i["x"], "top": i["top"]} for i in images],
            "graphics": _merge_boxes(graphics),
        })
    content = {"page_count": len(pages_content), "page_size": page_size, "pages": pages_content}
    return CanonicalPdf(content=content, layout={"pages": pages_layout})


def compare_layout(a: CanonicalPdf, b: CanonicalPdf) -> dict:
    """Maximum positional deviation (in points) between two PDFs with the same content structure."""
    deviations = {"lines": 0.0, "images": 0.0, "graphics": 0.0, "graphics_count_mismatch": []}
    for page_index, (pa, pb) in enumerate(zip(a.layout["pages"], b.layout["pages"])):
        for la, lb in zip(pa["lines"], pb["lines"]):
            deviations["lines"] = max(deviations["lines"], abs(la["x"] - lb["x"]), abs(la["baseline"] - lb["baseline"]))
        for ia, ib in zip(pa["images"], pb["images"]):
            deviations["images"] = max(deviations["images"], abs(ia["x"] - ib["x"]), abs(ia["top"] - ib["top"]))
        if len(pa["graphics"]) != len(pb["graphics"]):
            deviations["graphics_count_mismatch"].append(
                {"page": page_index + 1, "a": len(pa["graphics"]), "b": len(pb["graphics"])})
        for ga, gb in zip(pa["graphics"], pb["graphics"]):
            deviations["graphics"] = max(deviations["graphics"], *(abs(x - y) for x, y in zip(ga, gb)))
    return {k: (round(v, 2) if isinstance(v, float) else v) for k, v in deviations.items()}
