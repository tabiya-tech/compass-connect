"""
Canonical (normalized) representation of a skills report DOCX, used to compare documents generated by different
libraries (docx.js in the frontend, python-docx in the backend).

A DOCX is a zip of XML parts. Their bytes differ between libraries (namespaces, attribute order, part names,
relationship ids, timestamps, zip compression), so the comparison is done on the document model:

  - the default run/paragraph properties and the definition of every style used by the document
  - the page setup of the section (size, margins, header/footer distance)
  - the default header, the body and the default footer as lists of paragraphs with their properties
    (style, alignment, spacing, keep-with-next, page-break-before, borders) and runs
    (bold, italic, caps, colour, size, font, and the run content: text, breaks, fields, images)
  - images are identified by the SHA-256 of their bytes and their display size (EMU)

Normalizations (documented differences that are not visible to the reader):
  - a header/footer that only contains empty paragraphs is treated as empty (docx.js writes no paragraph at all,
    which is invalid OOXML; python-docx writes one empty paragraph)
  - complex fields (fldChar begin/instrText/separate/end) are reduced to their instruction, e.g. {"field": "PAGE"}
"""
# pylint: disable=c-extension-no-member
import hashlib
import json
import posixpath
import zipfile
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

# Only parses the DOCX files generated by the parity run, with a hardened parser (see _PARSER)
from lxml import etree  # nosec B410

# No entity resolution, no network access, no huge trees
_PARSER = etree.XMLParser(resolve_entities=False, no_network=True, huge_tree=False)


def _parse_xml(data: bytes):
    return etree.fromstring(data, parser=_PARSER)  # nosec B320

W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
R = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"
WP = "http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing"
A = "http://schemas.openxmlformats.org/drawingml/2006/main"
PKG_REL = "http://schemas.openxmlformats.org/package/2006/relationships"
NS = {"w": W, "r": R, "wp": WP, "a": A}

_FALSE_VALUES = {"false", "0", "off"}


def _w(tag: str) -> str:
    return f"{{{W}}}{tag}"


@dataclass
class CanonicalDocx:
    content: dict

    @property
    def content_hash(self) -> str:
        return hashlib.sha256(json.dumps(self.content, sort_keys=True, ensure_ascii=False).encode("utf-8")).hexdigest()


def _on_off(parent, tag: str) -> Optional[bool]:
    el = parent.find(f"w:{tag}", NS) if parent is not None else None
    if el is None:
        return None
    return el.get(_w("val"), "true").lower() not in _FALSE_VALUES


def _val(parent, tag: str) -> Optional[str]:
    el = parent.find(f"w:{tag}", NS) if parent is not None else None
    return None if el is None else el.get(_w("val"))


def _drop_none(d: dict) -> dict:
    return {k: v for k, v in d.items() if v is not None and v != {} and v != []}


def _run_properties(r_pr) -> dict:
    if r_pr is None:
        return {}
    fonts = r_pr.find("w:rFonts", NS)
    sz = _val(r_pr, "sz")
    return _drop_none({
        "style": _val(r_pr, "rStyle"),
        "bold": _on_off(r_pr, "b"),
        "italic": _on_off(r_pr, "i"),
        "caps": _on_off(r_pr, "caps"),
        "underline": _val(r_pr, "u"),
        "color": (_val(r_pr, "color") or "").upper() or None,
        "size": int(sz) if sz is not None else None,
        "font": None if fonts is None else _drop_none({k: fonts.get(_w(k)) for k in ("ascii", "hAnsi", "eastAsia",
                                                                                      "cs")}),
        "vertAlign": _val(r_pr, "vertAlign"),
    })


def _paragraph_properties(p_pr) -> dict:
    if p_pr is None:
        return {}
    spacing = p_pr.find("w:spacing", NS)
    borders = {}
    p_bdr = p_pr.find("w:pBdr", NS)
    if p_bdr is not None:
        for side in p_bdr:
            borders[etree.QName(side).localname] = _drop_none({
                "style": side.get(_w("val")), "size": side.get(_w("sz")), "space": side.get(_w("space")),
                "color": (side.get(_w("color")) or "").upper() or None})
    return _drop_none({
        "style": _val(p_pr, "pStyle"),
        "alignment": _val(p_pr, "jc"),
        "spacing": None if spacing is None else _drop_none({k: spacing.get(_w(k)) for k in ("before", "after", "line",
                                                                                            "lineRule")}),
        "keepNext": _on_off(p_pr, "keepNext"),
        "keepLines": _on_off(p_pr, "keepLines"),
        "pageBreakBefore": _on_off(p_pr, "pageBreakBefore"),
        "borders": borders,
        "indent": None if p_pr.find("w:ind", NS) is None else dict(sorted(
            (etree.QName(k).localname, v) for k, v in p_pr.find("w:ind", NS).attrib.items())),
    })


class _Part:
    def __init__(self, zf: zipfile.ZipFile, name: str):
        self.zf = zf
        self.name = name
        self.xml = _parse_xml(zf.read(name))
        rels_name = posixpath.join(posixpath.dirname(name), "_rels", posixpath.basename(name) + ".rels")
        self.rels: dict[str, str] = {}
        if rels_name in zf.namelist():
            for rel in _parse_xml(zf.read(rels_name)):
                target = rel.get("Target")
                if rel.get("TargetMode") != "External":
                    target = posixpath.normpath(posixpath.join(posixpath.dirname(name), target)) \
                        if not target.startswith("/") else target.lstrip("/")
                self.rels[rel.get("Id")] = target

    def image(self, r_id: str) -> str:
        return hashlib.sha256(self.zf.read(self.rels[r_id])).hexdigest()


def _run_content(part: _Part, r) -> list:
    items: list = []
    field_state = None  # None | "instr" | "result"
    for child in r:
        tag = etree.QName(child).localname
        if tag == "rPr":
            continue
        if tag == "fldChar":
            kind = child.get(_w("fldCharType"))
            if kind == "begin":
                field_state = "instr"
                items.append({"field": ""})
            elif kind == "separate":
                field_state = "result"
            elif kind == "end":
                field_state = None
            continue
        if tag == "instrText" and field_state == "instr":
            items[-1]["field"] += (child.text or "").strip()
            continue
        if field_state == "result":
            continue  # cached field result
        if tag == "t":
            text = child.text or ""
            if items and "text" in items[-1]:
                items[-1]["text"] += text
            else:
                items.append({"text": text})
        elif tag == "br":
            items.append({"break": child.get(_w("type"), "textWrapping")})
        elif tag == "tab":
            items.append({"tab": True})
        elif tag == "drawing":
            extent = child.find(".//wp:extent", NS)
            blip = child.find(".//a:blip", NS)
            items.append({"image": {
                "sha256": part.image(blip.get(f"{{{R}}}embed")) if blip is not None else None,
                "cx": int(extent.get("cx")) if extent is not None else None,
                "cy": int(extent.get("cy")) if extent is not None else None,
            }})
    return items


def _blocks(part: _Part, container) -> list[dict]:
    blocks = []
    for p in container.findall("w:p", NS):
        runs = []
        for r in p.findall("w:r", NS):
            content = _run_content(part, r)
            runs.append(_drop_none({"props": _run_properties(r.find("w:rPr", NS)), "content": content}))
        blocks.append(_drop_none({"props": _paragraph_properties(p.find("w:pPr", NS)), "runs": runs}))
    if container.findall("w:tbl", NS):
        blocks.append({"unsupported": "tables"})
    return blocks


def _is_empty_story(blocks: list[dict]) -> bool:
    return all(not b.get("runs") for b in blocks)


def _styles(zf: zipfile.ZipFile, used_style_ids: set[str]) -> dict:
    xml = _parse_xml(zf.read("word/styles.xml"))
    doc_defaults = xml.find("w:docDefaults", NS)
    r_pr_default = doc_defaults.find("w:rPrDefault/w:rPr", NS) if doc_defaults is not None else None
    p_pr_default = doc_defaults.find("w:pPrDefault/w:pPr", NS) if doc_defaults is not None else None
    styles = {}
    by_id = {s.get(_w("styleId")): s for s in xml.findall("w:style", NS)}
    pending = list(used_style_ids)
    while pending:
        style_id = pending.pop()
        style = by_id.get(style_id)
        if style is None or style_id in styles:
            if style is None:
                styles[style_id] = {"missing": True}
            continue
        based_on = _val(style, "basedOn")
        styles[style_id] = _drop_none({
            "type": style.get(_w("type")),
            "name": _val(style, "name"),
            "basedOn": based_on,
            "run": _run_properties(style.find("w:rPr", NS)),
            "paragraph": _paragraph_properties(style.find("w:pPr", NS)),
        })
        if based_on and based_on not in styles:
            pending.append(based_on)
    return {
        "defaults": {"run": _run_properties(r_pr_default), "paragraph": _paragraph_properties(p_pr_default)},
        "styles": styles,
    }


def _referenced_part(part: _Part, sect_pr, tag: str) -> Optional[str]:
    for ref in sect_pr.findall(f"w:{tag}", NS):
        if ref.get(_w("type"), "default") == "default":
            return part.rels.get(ref.get(f"{{{R}}}id"))
    return None


def canonicalize_docx(path: Path) -> CanonicalDocx:
    with zipfile.ZipFile(path) as zf:
        content_types = _parse_xml(zf.read("[Content_Types].xml"))
        main_name = next(o.get("PartName") for o in content_types
                         if o.get("ContentType", "").endswith("document.main+xml")).lstrip("/")
        document = _Part(zf, main_name)
        body = document.xml.find("w:body", NS)
        sect_pr = body.find("w:sectPr", NS)

        stories = {"body": _blocks(document, body)}
        for tag, key in (("headerReference", "header"), ("footerReference", "footer")):
            name = _referenced_part(document, sect_pr, tag) if sect_pr is not None else None
            if name is None:
                stories[key] = []
                continue
            story_part = _Part(zf, name)
            blocks = _blocks(story_part, story_part.xml)
            stories[key] = [] if _is_empty_story(blocks) else blocks

        used_styles = set()
        for blocks in stories.values():
            for block in blocks:
                if block.get("props", {}).get("style"):
                    used_styles.add(block["props"]["style"])
                for run in block.get("runs", []):
                    if run.get("props", {}).get("style"):
                        used_styles.add(run["props"]["style"])

        section = {}
        if sect_pr is not None:
            pg_sz = sect_pr.find("w:pgSz", NS)
            pg_mar = sect_pr.find("w:pgMar", NS)
            section = _drop_none({
                "pageSize": None if pg_sz is None else _drop_none({
                    "width": pg_sz.get(_w("w")), "height": pg_sz.get(_w("h")),
                    "orientation": pg_sz.get(_w("orient"), "portrait")}),
                "margins": None if pg_mar is None else {etree.QName(k).localname: v
                                                        for k, v in sorted(pg_mar.attrib.items())},
            })

        content = {
            "styles": _styles(zf, used_styles),
            "section": section,
            "header": stories["header"],
            "body": stories["body"],
            "footer": stories["footer"],
        }
    return CanonicalDocx(content=content)
