"""
Tests of the react-pdf textkit port. The expected values were taken from PDFs generated by the frontend (react-pdf).
"""
import pytest

from app.skills_report import assets
from app.skills_report.pdf.hyphenation import hyphenate, word_syllables
from app.skills_report.pdf.text_kit import Attributes, Fragment, layout_text, load_font

_BODY_TEXT = ("This report summarizes the key information gathered during a conversation with Compass on March 14, "
              "2025. Compass is an AI chatbot that assists job-seekers in exploring their skills and experiences. "
              "This report presents the candidate’s work experience and the skills identified from each experience. "
              "This information can be used to guide job search and highlight their skills when applying for jobs, "
              "especially during interviews with potential employers. It can be a good starting point for creating "
              "a complete CV.")


@pytest.fixture(name="regular_font")
def _regular_font():
    return load_font(assets.INTER.regular, "Inter-Regular")


class TestHyphenation:
    @pytest.mark.parametrize("word, expected", [
        ("hyphenation", ["hy", "phen", "ation"]),
        ("reconciliation", ["rec", "on", "cil", "i", "a", "tion"]),
        ("table", ["ta", "ble"]),  # pattern exception
        ("needs,", ["needs,"]),  # too short (min word length 5)
        ("ab­cd", ["ab", "cd"]),  # existing soft hyphens are kept as is
    ])
    def test_splits_words_into_syllables_like_the_hyphen_package(self, word, expected):
        # GIVEN a word
        # WHEN it is split into syllables
        actual = word_syllables(word)
        # THEN the syllables are the ones of the `hyphen` npm package (en-us patterns)
        assert actual == expected

    def test_does_not_hyphenate_html_tags(self):
        # GIVEN a text with an HTML-like tag
        # WHEN it is hyphenated
        actual = hyphenate("<strong>information</strong>")
        # THEN the tag is left untouched, only the word is hyphenated (same as the `hyphen` npm package)
        assert actual.split("\u00ad") == ["<strong>in", "for", "ma", "tion</strong>"]


class TestLayoutText:
    def test_breaks_lines_like_react_pdf(self, regular_font):
        # GIVEN the report body text at 11pt
        given_fragments = [Fragment(_BODY_TEXT, Attributes(regular_font, 11))]
        # WHEN it is laid out in the report content width
        lines = layout_text(given_fragments, 499.28)
        # THEN the lines are broken where react-pdf breaks them (Knuth & Plass)
        assert [line.string for line in lines] == [
            "This report summarizes the key information gathered during a conversation with Compass on ",
            "March 14, 2025. Compass is an AI chatbot that assists job-seekers in exploring their skills and ",
            "experiences. This report presents the candidate’s work experience and the skills identified from ",
            "each experience. This information can be used to guide job search and highlight their skills when ",
            "applying for jobs, especially during interviews with potential employers. It can be a good starting ",
            "point for creating a complete CV.",
        ]
        # AND the line height is the natural line height of Inter (ascent - descent)
        assert lines[0].box.height == pytest.approx(13.31, abs=0.01)

    def test_shrinks_only_the_spaces_of_an_overflowing_line(self, regular_font):
        # GIVEN a line of text that is slightly wider than the available width
        given_text = "Listed skills are based on a conversation with the candidate, are not verified"
        natural = layout_text([Fragment(given_text, Attributes(regular_font, 9))], 1000)[0].x_advance
        # WHEN it is laid out in a width that is 1pt narrower
        lines = layout_text([Fragment(given_text, Attributes(regular_font, 9))], natural - 1)
        # THEN it stays on one line, justified to the available width
        assert len(lines) == 1
        assert lines[0].x_advance == pytest.approx(natural - 1, abs=0.001)

    def test_splits_paragraphs_on_new_lines(self, regular_font):
        # GIVEN a text with a new line
        given_fragments = [Fragment("First paragraph\nSecond paragraph", Attributes(regular_font, 10))]
        # WHEN it is laid out
        lines = layout_text(given_fragments, 400)
        # THEN each paragraph starts on its own line, without the new line character
        assert [line.string for line in lines] == ["First paragraph", "Second paragraph"]

    def test_centers_lines(self, regular_font):
        # GIVEN a centered page number
        given_fragments = [Fragment("1 / 3", Attributes(regular_font, 10, align="center"))]
        # WHEN it is laid out on the page width
        lines = layout_text(given_fragments, 595.28)
        # THEN it is centered like in the frontend report (x = 287.9)
        assert lines[0].box.x == pytest.approx(287.9, abs=0.05)
